import { Router } from 'express'
import { getCard } from '../../domain/accounts.js'
import { audit } from '../../domain/audit.js'
import { confirmIntent, createIntent, setPin } from '../../domain/pos.js'
import type { OrderRequestItem, PayMethod } from '../../domain/orders.js'
import { businessDay } from '../../domain/businessDay.js'
import { isPayMethod, renderReceipt } from '../../domain/receipt.js'
import {
  allocateReceiptNumber,
  markRendered,
  releaseReceiptNumber,
  UnknownOrderError
} from '../../domain/receiptNumbers.js'
import { param, pushBalanceForCard, type StaffDeps } from '../deps.js'
import { requireRole } from '../staffAuth.js'

/**
 * Point of sale: staff take an order face-to-face and the customer taps their
 * card on the same Android tablet (Web NFC).
 *
 * Two steps on purpose. `intent` prices the cart and decides server-side whether
 * this payment is one of the 1-in-8 that gets PIN-checked; `confirm` charges it.
 * If the client made that decision it would simply never ask for a PIN.
 *
 * Ordinary staff may take payments — they run the bar. Only admins set PINs.
 */
export function posRouter(deps: StaffDeps): Router {
  const router = Router()

  router.post('/pos/intent', (req, res) => {
    // Note what is NOT read here: the PIN decision. It comes from deps, never
    // from the body — see StaffDeps.posPinDecision.
    const { cardUid, items, pay, customAmountDeni, label, direction } = req.body ?? {}

    if (typeof cardUid !== 'string' || cardUid.trim() === '') {
      res.status(400).json({ ok: false, code: 'unknown_card', error: 'cardUid is required' })
      return
    }

    const isCustom = customAmountDeni !== undefined

    if (isCustom) {
      if (!Number.isInteger(customAmountDeni) || customAmountDeni <= 0 || customAmountDeni > 5_000_000) {
        res.status(400).json({ ok: false, error: 'customAmountDeni must be a positive integer (max 5000000)' })
        return
      }
      if (direction !== undefined && direction !== 'debit' && direction !== 'credit') {
        res.status(400).json({ ok: false, error: 'direction must be debit or credit' })
        return
      }
    } else {
      if (!Array.isArray(items)) {
        res.status(400).json({ ok: false, code: 'empty', error: 'items must be an array' })
        return
      }
    }

    const result = createIntent(deps.db, {
      cardUid,
      ...(isCustom
        ? {
            customAmountDeni,
            label: typeof label === 'string' ? label : undefined,
            direction: direction as 'debit' | 'credit' | undefined
          }
        : {
            items: items as OrderRequestItem[],
            pay: pay === 'points' ? 'points' : ('cash' as PayMethod)
          }),
      staff: req.staff!.username,
      ...(deps.posPinDecision ? { forcePin: deps.posPinDecision() } : {})
    })

    if (!result.ok) {
      res.status(400).json(result)
      return
    }
    res.json(result)
  })

  router.post('/pos/confirm', (req, res) => {
    const { intentId, pin } = req.body ?? {}
    if (typeof intentId !== 'string' || intentId.trim() === '') {
      res.status(400).json({ ok: false, code: 'unknown_intent', error: 'intentId is required' })
      return
    }

    const result = confirmIntent(deps.db, {
      intentId,
      ...(typeof pin === 'string' ? { pin } : {})
    })

    if (!result.ok) {
      res.status(400).json(result)
      return
    }

    audit(deps.db, {
      actor: req.staff!.username,
      action: result.direction === 'credit' ? 'pos.credit' : 'pos.charge',
      entityType: result.orderId ? 'order' : 'intent',
      entityId: result.orderId ?? intentId,
      details: { cardId: result.cardId, balanceDeni: result.balanceDeni }
    })

    // Keep a terminal that's mid-session from showing a stale balance, and put
    // the drink on the bar's live feed.
    pushBalanceForCard(deps, result.cardId)
    if (result.orderId) {
      deps.events.emit('order.created', { orderId: result.orderId })
    }

    res.json(result)
  })

  /**
   * Fiscal receipt image for the guest's printer, generated by the external
   * Receipt Render API. Proxied so its x-api-key never reaches the browser.
   * Any signed-in staff member may print — same gate as the payment routes.
   *
   * Not in audit_log, but no longer unrecorded: the receipts table is the record
   * of what printed, and it is the fiscal one.
   */
  router.post('/pos/receipt', async (req, res) => {
    const { items, payMethod, orderId } = req.body ?? {}
    if (!Array.isArray(items) || items.length === 0) {
      res.status(400).json({ error: 'items must be a non-empty array' })
      return
    }
    // Fail closed rather than defaulting. An absent tender line is precisely how every
    // денари sale used to print as ВО ГОТОВО: the render API fills what it is not sent from
    // its own preset, so a malformed request produced a plausible, wrong fiscal document.
    // No receipt is a failure the barman sees and retries; a wrong one is not. It costs a
    // receipt and never a sale — printing runs after the card is already charged.
    if (!isPayMethod(payMethod)) {
      res.status(400).json({ error: 'payMethod must be cash or points' })
      return
    }
    // The number is recorded against the sale, so there has to be a sale. A pos credit
    // has no order and so can never be printed — until now a client-side convention.
    if (typeof orderId !== 'string' || orderId.trim() === '') {
      res.status(400).json({ error: 'orderId is required' })
      return
    }

    const day = businessDay(deps.config.timeZone, deps.now?.() ?? new Date())
    let number
    try {
      number = allocateReceiptNumber(deps.db, {
        orderId,
        day,
        timeZone: deps.config.timeZone,
        actor: req.staff!.username
      })
    } catch (e) {
      if (e instanceof UnknownOrderError) {
        res.status(404).json({ error: 'no such order' })
        return
      }
      throw e
    }

    // The number has to be committed before the render, because it goes *into* the
    // request and better-sqlite3 cannot hold a transaction across an await. So every
    // way out of here either marks it printed or gives it back: a number burned by a
    // failed render is a hole in a fiscal sequence, and holes are what get questioned.
    // A reused number belongs to a receipt that already printed — never release that.
    let result
    try {
      result = await renderReceipt(deps.config, { items, payMethod, receiptNumber: number.printed })
    } catch {
      // fetch rejects outright on a dead network. Before this was caught the promise
      // went unhandled and the request simply hung until the tablet gave up.
      if (!number.reused) releaseReceiptNumber(deps.db, number.id)
      res.status(502).json({ error: 'receipt rendering failed', code: 'upstream_error' })
      return
    }

    if (!result.ok) {
      if (!number.reused) releaseReceiptNumber(deps.db, number.id)
      res.status(result.status).json({ error: result.error ?? 'receipt rendering failed', code: result.code })
      return
    }

    markRendered(deps.db, number.id)
    res.set('Content-Type', result.contentType)
    res.set('Cache-Control', 'no-store')
    // Saves the done screen a second round trip just to name the receipt it printed.
    res.set('X-Receipt-Number', number.printed)
    res.send(result.png)
  })

  router.post('/cards/:id/pin', requireRole('admin'), (req, res) => {
    const cardId = param(req, 'id')
    if (!getCard(deps.db, cardId)) {
      res.status(404).json({ error: 'no such card' })
      return
    }

    const { pin } = req.body ?? {}
    if (typeof pin !== 'string' || !/^[0-9]{4}$/.test(pin)) {
      res.status(400).json({ error: 'pin must be exactly 4 digits' })
      return
    }

    setPin(deps.db, cardId, pin)
    // Deliberately records only that a PIN was set — never the PIN itself.
    audit(deps.db, {
      actor: req.staff!.username,
      action: 'card.set_pin',
      entityType: 'card',
      entityId: cardId
    })
    res.json({ ok: true })
  })

  return router
}
